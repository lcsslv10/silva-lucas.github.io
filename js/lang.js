document.addEventListener("DOMContentLoaded", () => {
    const toggleBtn = document.getElementById("lang-toggle");
    const langLabel = document.getElementById("lang-label");
    const langIcon = document.getElementById("lang-icon");
    if (!toggleBtn) return;

    const IMG_EN = "images/lang-en.png";
    const IMG_FR = "images/lang-fr.png";

    const CV_FR = "docs/CV_Lucas_Silva.pdf";
    const CV_EN = "docs/cv-english.pdf";

    const nodes = [];
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
        const parent = node.parentElement;
        if (!parent) continue;
        if (parent.closest("script, style, #lang-toggle, .notranslate, code, pre")) continue;

        const raw = node.nodeValue;
        const trimmed = raw.trim();
        if (DICT_EN[trimmed]) {
            nodes.push({
                node,
                frRaw: raw,
                enRaw: raw.replace(trimmed, DICT_EN[trimmed])
            });
        }
    }

    const cvLinks = document.querySelectorAll('a[href*="CV_Lucas_Silva.pdf"], a[href*="cv-english.pdf"]');

    const applyLang = (lang) => {
        document.documentElement.lang = lang;
        const isEn = lang === "en";

        nodes.forEach(({ node, frRaw, enRaw }) => {
            node.nodeValue = isEn ? enRaw : frRaw;
        });

        cvLinks.forEach((link) => {
            link.setAttribute("href", isEn ? CV_EN : CV_FR);
        });

        if (langLabel) langLabel.textContent = isEn ? "FR" : "EN";
        if (langIcon) langIcon.src = isEn ? IMG_FR : IMG_EN;
        toggleBtn.setAttribute("aria-label", isEn ? "Passer en français" : "Switch to English");
    };

    let current = localStorage.getItem("portfolio_lang") || "fr";
    applyLang(current);

    toggleBtn.addEventListener("click", () => {
        current = current === "fr" ? "en" : "fr";
        localStorage.setItem("portfolio_lang", current);
        applyLang(current);
    });
});